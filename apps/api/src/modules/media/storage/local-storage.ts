import { mkdir, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import type { Bucket, StorageProvider } from './storage.provider.js';

/**
 * Development storage: files on disk under `<root>/<bucket>/<key>`. The public bucket is
 * served by the API at MEDIA_PUBLIC_URL (see mount-media.ts).
 */
export class LocalStorage implements StorageProvider {
  constructor(private readonly root: string) {}

  bucketDir(bucket: Bucket): string {
    return resolve(this.root, bucket);
  }

  async put(bucket: Bucket, key: string, body: Buffer): Promise<void> {
    const path = this.pathFor(bucket, key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, body);
  }

  async delete(bucket: Bucket, key: string): Promise<void> {
    await rm(this.pathFor(bucket, key), { force: true });
  }

  private pathFor(bucket: Bucket, key: string): string {
    const base = this.bucketDir(bucket);
    const path = resolve(base, key);
    // Keys are generated by the server, but never allow escaping the bucket folder.
    if (!path.startsWith(base)) throw new Error(`Invalid storage key: ${key}`);
    return path;
  }
}
